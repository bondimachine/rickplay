#!/usr/bin/env python3
"""Tiny NE (Win16) linker for rickplay.asm.

  mkne.py inc  <imports.inc>            write the import table include file
  mkne.py link <flat.bin> <out.exe>     wrap NASM's flat output into an NE exe

flat.bin layout (see rickplay.asm): code segment at 0 with a small header
  +0 code length, +2 file offset of data segment, +4 initialized data length,
  +6 entry IP, +8 data segment size including uninitialized buffers,
  +12 import table (4 bytes per import, in IMPORTS order),
followed by the data segment.

Both segments are FIXED: real-mode Windows then never moves our code or data,
so far return addresses into our code and our DS stay valid.
The menu and the Open dialog are built here as NE resources.
"""
import struct, sys

# (module, name, ordinal) - ordinals verified against Windows 3.0 KERNEL/USER/GDI
IMPORTS = [
    ("KERNEL", "INITTASK", 91), ("KERNEL", "WAITEVENT", 30),
    ("KERNEL", "GETMODULEFILENAME", 49), ("KERNEL", "_LOPEN", 85),
    ("KERNEL", "_LREAD", 82), ("KERNEL", "_LCLOSE", 81), ("KERNEL", "_LLSEEK", 84),
    ("KERNEL", "_LCREAT", 83), ("KERNEL", "_LWRITE", 86),
    ("KERNEL", "GLOBALALLOC", 15), ("KERNEL", "GLOBALLOCK", 18), ("KERNEL", "GLOBALUNLOCK", 19),
    ("KERNEL", "GLOBALFREE", 17),
    ("USER", "INITAPP", 5), ("USER", "REGISTERCLASS", 57), ("USER", "CREATEWINDOW", 41),
    ("USER", "SHOWWINDOW", 42), ("USER", "UPDATEWINDOW", 124), ("USER", "PEEKMESSAGE", 109),
    ("USER", "TRANSLATEMESSAGE", 113), ("USER", "DISPATCHMESSAGE", 114),
    ("USER", "DEFWINDOWPROC", 107), ("USER", "POSTQUITMESSAGE", 6), ("USER", "GETDC", 66),
    ("USER", "RELEASEDC", 68), ("USER", "BEGINPAINT", 39), ("USER", "ENDPAINT", 40),
    ("USER", "GETCURRENTTIME", 15), ("USER", "LOADCURSOR", 173),
    ("USER", "ADJUSTWINDOWRECT", 102), ("USER", "MESSAGEBOX", 1), ("USER", "EXITWINDOWS", 7),
    ("USER", "DESTROYWINDOW", 53), ("USER", "ISICONIC", 31), ("USER", "WAITMESSAGE", 112),
    ("USER", "DIALOGBOX", 87), ("USER", "ENDDIALOG", 88), ("USER", "DLGDIRLIST", 100),
    ("USER", "DLGDIRSELECT", 99), ("USER", "SETDLGITEMTEXT", 92), ("USER", "GETDLGITEMTEXT", 93),
    ("USER", "SETWINDOWPOS", 232), ("USER", "SENDDLGITEMMESSAGE", 101), ("USER", "SETWINDOWTEXT", 37), ("USER", "INVALIDATERECT", 125),
    ("GDI", "CREATECOMPATIBLEDC", 52), ("GDI", "CREATEBITMAP", 48), ("GDI", "SELECTOBJECT", 45),
    ("GDI", "SETBITMAPBITS", 106), ("GDI", "BITBLT", 34), ("GDI", "DELETEDC", 68),
    ("GDI", "DELETEOBJECT", 69), ("GDI", "GETSTOCKOBJECT", 87),
]
MODULES = ["KERNEL", "USER", "GDI"]
HEAP, STACK = 0x0400, 0x1800
IMPORT_BASE = 12

# ---- resources (ids must match rickplay.asm)
IDM_OPEN, IDM_EXIT, IDM_ABOUT = 100, 101, 102
IDC_NAME, IDC_PATH, IDC_LIST = 10, 11, 12
MF_POPUP, MF_END, MF_SEPARATOR = 0x10, 0x80, 0x800

def sz(s):
    return s.encode("latin1") + b"\0"

def menu_resource():
    m = struct.pack("<HH", 0, 0)
    m += struct.pack("<H", MF_POPUP) + sz("&File")
    m += struct.pack("<HH", 0, IDM_OPEN) + sz("&Open...")
    m += struct.pack("<HH", MF_SEPARATOR, 0) + sz("")
    m += struct.pack("<HH", MF_END, IDM_EXIT) + sz("E&xit")
    m += struct.pack("<H", MF_POPUP | MF_END) + sz("&Help")
    m += struct.pack("<HH", MF_END, IDM_ABOUT) + sz("&About RickPlay...")
    return m

def dialog_resource():
    WS_CHILD_VIS, WS_BORDER, WS_VSCROLL, WS_TABSTOP = 0x50000000, 0x00800000, 0x00200000, 0x00010000
    BUTTON, EDIT, STATIC, LISTBOX = 0x80, 0x81, 0x82, 0x83
    items = [  # x, y, cx, cy, id, style, class, text   (dialog units)
        (6, 6, 42, 10, 0xFFFF, WS_CHILD_VIS, STATIC, "File&name:"),
        (50, 5, 116, 12, IDC_NAME, WS_CHILD_VIS | WS_BORDER | WS_TABSTOP | 0x80, EDIT, ""),
        (6, 21, 42, 10, 0xFFFF, WS_CHILD_VIS, STATIC, "Directory:"),
        (50, 21, 116, 10, IDC_PATH, WS_CHILD_VIS | 0x80, STATIC, ""),
        (6, 35, 100, 10, 0xFFFF, WS_CHILD_VIS, STATIC, "&Files:"),
        (6, 46, 100, 62, IDC_LIST, WS_CHILD_VIS | WS_BORDER | WS_VSCROLL | WS_TABSTOP | 0x3, LISTBOX, ""),
        (116, 46, 50, 14, 1, WS_CHILD_VIS | WS_TABSTOP | 0x1, BUTTON, "OK"),
        (116, 66, 50, 14, 2, WS_CHILD_VIS | WS_TABSTOP, BUTTON, "Cancel"),
    ]
    style = 0x80000000 | 0x00C00000 | 0x00080000 | 0x80   # WS_POPUP|WS_CAPTION|WS_SYSMENU|DS_MODALFRAME
    d = struct.pack("<IB4H", style, len(items), 20, 10, 172, 114) + b"\0" + b"\0" + sz("Open")
    for x, y, cx, cy, i, st, cls, text in items:
        d += struct.pack("<5HIB", x, y, cx, cy, i, st, cls) + sz(text) + b"\0"
    return d

RESOURCES = [(4, 1, menu_resource()), (5, 1, dialog_resource())]   # (type, id, data)

def write_inc(path):
    with open(path, "w") as f:
        f.write("; generated by mkne.py - do not edit\n%macro IMPORT_TABLE 0\n")
        for _, name, _ in IMPORTS:
            f.write(f"  IMP {name}\n")
        f.write("%endmacro\n")

def pad16(b):
    return b + b"\0" * (-len(b) % 16)

def mz_stub():
    msg = b"This program requires Microsoft Windows.\r\n$"
    code = bytes([0x0E, 0x1F, 0xBA, 14, 0, 0xB4, 0x09, 0xCD, 0x21, 0xB8, 0x01, 0x4C, 0xCD, 0x21]) + msg
    size = 0x40 + len(code)
    hdr = bytearray(0x40)
    struct.pack_into("<2s13H", hdr, 0, b"MZ", size % 512, (size + 511) // 512, 0, 4, 0, 0xFFFF,
                     0, 0xB8, 0, 0, 0, 0x40, 0)
    return hdr, code

def resource_table(offsets):
    t = struct.pack("<H", 4)                                 # alignment shift
    for (rtype, rid, data), off in zip(RESOURCES, offsets):
        t += struct.pack("<HHI", 0x8000 | rtype, 1, 0)
        t += struct.pack("<HHHHI", off >> 4, (len(data) + 15) >> 4,
                         0x1030, 0x8000 | rid, 0)            # moveable | pure | discardable
    return t + b"\0\0" + b"\0"                               # end of types, no names

def link(flat_path, out_path):
    flat = open(flat_path, "rb").read()
    code_len, data_start, data_len, entry_ip, data_alloc = struct.unpack_from("<5H", flat, 0)
    code = flat[:code_len]
    data = flat[data_start:data_start + data_len]
    if data_alloc + HEAP + STACK > 0x10000:
        sys.exit(f"DGROUP too big: {data_alloc:#x} + heap + stack")

    relocs = b""
    for i, (mod, _, ordinal) in enumerate(IMPORTS):
        # type 3 = 16:16 far pointer, flags 1 = imported ordinal; target holds 0xFFFF (chain end)
        relocs += struct.pack("<BBHHH", 3, 1, IMPORT_BASE + 4 * i, MODULES.index(mod) + 1, ordinal)
    relocs = struct.pack("<H", len(IMPORTS)) + relocs

    stub_hdr, stub_code = mz_stub()
    ne_off = len(pad16(bytes(stub_hdr) + stub_code))
    struct.pack_into("<I", stub_hdr, 0x3C, ne_off)

    # tables after the 64-byte NE header
    segtab_off = 0x40
    rsrc_off = segtab_off + 16
    rsrc_len = len(resource_table([0] * len(RESOURCES)))
    restab = bytes([8]) + b"RICKPLAY" + b"\0\0" + b"\0"
    imptab = b"\0"
    modref = b""
    for m in MODULES:
        modref += struct.pack("<H", len(imptab))
        imptab += bytes([len(m)]) + m.encode()
    entrytab = b"\0\0"
    res_off = rsrc_off + rsrc_len
    modref_off = res_off + len(restab)
    imp_off = modref_off + len(modref)
    entry_off = imp_off + len(imptab)
    desc = b"RickPlay - AVI player for Windows 3.0 real mode"
    nrestab = bytes([len(desc)]) + desc + b"\0\0" + b"\0"
    nres_abs = ne_off + entry_off + len(entrytab)

    code_abs = (nres_abs + len(nrestab) + 15) & ~15
    data_abs = (code_abs + len(code) + len(relocs) + 15) & ~15
    res_offsets, p = [], (data_abs + len(data) + 15) & ~15
    for _, _, rdata in RESOURCES:
        res_offsets.append(p)
        p = (p + len(rdata) + 15) & ~15
    rsrc = resource_table(res_offsets)

    segtab = struct.pack("<4H", code_abs >> 4, len(code), 0x0140, len(code))     # code, preload, relocs, fixed
    segtab += struct.pack("<4H", data_abs >> 4, len(data), 0x0041, data_alloc)   # data, preload, fixed

    ne = bytearray(0x40)
    struct.pack_into("<2sBBHHI" + "H" * 16 + "IHHHBBHHHH", ne, 0,
        b"NE", 5, 10, entry_off, len(entrytab), 0,
        0x0312,             # multiple data | 8086 | Windows API app (NOT protected-mode-only)
        2, HEAP, STACK,
        entry_ip, 1,        # CS:IP = seg 1 : entry
        0, 2,               # SS:SP = seg 2 : 0 (loader puts stack after data+heap)
        2, len(MODULES), len(nrestab),
        segtab_off, rsrc_off, res_off, modref_off, imp_off, nres_abs,
        0, 4, 0, 2, 0, 0, 0, 0, 0x0300)

    out = bytearray(pad16(bytes(stub_hdr) + stub_code))
    out += ne + segtab + rsrc + restab + modref + imptab + entrytab
    assert len(out) == nres_abs
    out += nrestab
    out += b"\0" * (code_abs - len(out))
    out += code + relocs
    out += b"\0" * (data_abs - len(out))
    out += data
    for (_, _, rdata), off in zip(RESOURCES, res_offsets):
        out += b"\0" * (off - len(out))
        out += rdata
    out += b"\0" * (-len(out) % 16)
    open(out_path, "wb").write(out)
    print(f"{out_path}: {len(out)} bytes (code {len(code)}, data {len(data)}, DGROUP {data_alloc + HEAP + STACK})")

if __name__ == "__main__":
    if sys.argv[1] == "inc":
        write_inc(sys.argv[2])
    else:
        link(sys.argv[2], sys.argv[3])
