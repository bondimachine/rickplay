#!/usr/bin/env python3
"""Generate src/tables.inc: lookup tables the 8088 decoder uses so that turning
a Microsoft Video 1 colour into dithered CGA pixels is a few XLATs.

Each source pixel becomes 2 horizontal output pixels (CGA 640x200 pixels are
tall and narrow), so a 4x4 source block is exactly one byte wide x 4 rows.

  pat     33 dither levels x 4 rows: one output byte per block row (MSB = left)
  tabLo   RGB555 low byte  -> partial grey  (blue + low green bits)
  tabHi   RGB555 high byte -> partial grey  (red + high green bits, bit 7 ignored)
          tabLo[lo] + tabHi[hi] = grey 0..255 (never overflows a byte)
  tabLvl  grey 0..255 -> offset of its pattern in pat (level * 4)
  expandLo / expandHi
          flag byte -> 8 output bits for the row in its low / high nibble
          (bit 0 = leftmost pixel, each pixel doubled)
"""
import sys

BAYER8 = [
    [0, 32, 8, 40, 2, 34, 10, 42], [48, 16, 56, 24, 50, 18, 58, 26],
    [12, 44, 4, 36, 14, 46, 6, 38], [60, 28, 52, 20, 62, 30, 54, 22],
]
LEVELS = 32          # 33 patterns: 0 (black) .. 32 (white)
BLACK, WHITE = 16, 235   # mild contrast stretch

def rows(name, data, per=16):
    out = [f"{name}:"]
    for i in range(0, len(data), per):
        out.append("        db " + ", ".join(f"{b:3d}" for b in data[i:i + per]))
    return "\n".join(out)

def main(path):
    # rank the 32 cells of a 4x8 Bayer tile -> thresholds 0..31
    cells = sorted((BAYER8[r][c], r, c) for r in range(4) for c in range(8))
    rank = {(r, c): i for i, (_, r, c) in enumerate(cells)}
    pat = []
    for lvl in range(LEVELS + 1):
        for r in range(4):
            b = 0
            for c in range(8):
                if rank[(r, c)] < lvl:
                    b |= 0x80 >> c
            pat.append(b)

    def g8(v5):
        return v5 * 255 / 31
    # grey = (2R + 5G + B) / 8, split across the two bytes of an RGB555 word
    tab_lo = [int((5 * g8(lo >> 5) + g8(lo & 31)) / 8) for lo in range(256)]
    tab_hi = [int((2 * g8((hi >> 2) & 31) + 5 * g8((hi & 3) << 3)) / 8) for hi in range(256)]
    assert max(a + b for a in tab_lo for b in tab_hi) <= 255
    tab_lvl = []
    for g in range(256):
        x = min(1.0, max(0.0, (g - BLACK) / (WHITE - BLACK)))
        tab_lvl.append(round(x * LEVELS) * 4)
    def expand(n):
        b = 0
        for i in range(4):
            if n & (1 << i):
                b |= 0xC0 >> (2 * i)
        return b
    expand_lo = [expand(v & 15) for v in range(256)]
    expand_hi = [expand(v >> 4) for v in range(256)]

    with open(path, "w") as f:
        f.write("; generated by tools/gentables.py - do not edit\n")
        for name, data in (("pat", pat), ("tabLo", tab_lo), ("tabHi", tab_hi),
                           ("tabLvl", tab_lvl), ("expandLo", expand_lo), ("expandHi", expand_hi)):
            f.write(rows(name, data) + "\n")

if __name__ == "__main__":
    main(sys.argv[1])
